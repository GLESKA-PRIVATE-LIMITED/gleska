BEGIN;

CREATE TABLE IF NOT EXISTS public.financial_agent_conversations (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  employer_id UUID NOT NULL REFERENCES public.employer_profiles(id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'ACTIVE' CHECK (status = 'ACTIVE'),
  revision INTEGER NOT NULL DEFAULT 0 CHECK (revision >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT financial_agent_conversations_id_owner_unique
    UNIQUE (id, user_id, employer_id)
);

CREATE TABLE IF NOT EXISTS public.financial_agent_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id UUID NOT NULL,
  user_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  employer_id UUID NOT NULL REFERENCES public.employer_profiles(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('user', 'assistant')),
  content TEXT NOT NULL CHECK (char_length(content) BETWEEN 1 AND 4000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT financial_agent_messages_conversation_owner_fk
    FOREIGN KEY (conversation_id, user_id, employer_id)
    REFERENCES public.financial_agent_conversations(id, user_id, employer_id)
    ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_financial_agent_conversations_owner_updated
  ON public.financial_agent_conversations(user_id, employer_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_financial_agent_messages_owner_history
  ON public.financial_agent_messages(conversation_id, user_id, employer_id, id DESC);

DROP TRIGGER IF EXISTS update_financial_agent_conversations_updated_at
  ON public.financial_agent_conversations;
CREATE TRIGGER update_financial_agent_conversations_updated_at
  BEFORE UPDATE ON public.financial_agent_conversations
  FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

ALTER TABLE public.financial_agent_conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.financial_agent_messages ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Employers can access their Financial Agent conversations"
  ON public.financial_agent_conversations FOR ALL
  USING (
    user_id = auth.uid()
    AND EXISTS (
      SELECT 1 FROM public.employer_profiles ep
      WHERE ep.id = financial_agent_conversations.employer_id
        AND ep.user_id = auth.uid()
    )
  )
  WITH CHECK (
    user_id = auth.uid()
    AND EXISTS (
      SELECT 1 FROM public.employer_profiles ep
      WHERE ep.id = financial_agent_conversations.employer_id
        AND ep.user_id = auth.uid()
    )
  );
CREATE POLICY "Service role can access Financial Agent conversations"
  ON public.financial_agent_conversations FOR ALL
  USING (auth.role() = 'service_role')
  WITH CHECK (auth.role() = 'service_role');

CREATE POLICY "Employers can access their Financial Agent messages"
  ON public.financial_agent_messages FOR ALL
  USING (
    user_id = auth.uid()
    AND EXISTS (
      SELECT 1 FROM public.employer_profiles ep
      WHERE ep.id = financial_agent_messages.employer_id
        AND ep.user_id = auth.uid()
    )
  )
  WITH CHECK (
    user_id = auth.uid()
    AND EXISTS (
      SELECT 1 FROM public.employer_profiles ep
      WHERE ep.id = financial_agent_messages.employer_id
        AND ep.user_id = auth.uid()
    )
  );
CREATE POLICY "Service role can access Financial Agent messages"
  ON public.financial_agent_messages FOR ALL
  USING (auth.role() = 'service_role')
  WITH CHECK (auth.role() = 'service_role');

CREATE OR REPLACE FUNCTION public.append_financial_agent_turn(
  p_conversation_id UUID,
  p_user_id UUID,
  p_employer_id UUID,
  p_expected_revision INTEGER,
  p_user_message TEXT,
  p_assistant_message TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_conversation public.financial_agent_conversations%ROWTYPE;
  v_user_message JSONB;
  v_assistant_message JSONB;
BEGIN
  IF COALESCE(auth.role(), '') <> 'service_role' THEN
    RAISE EXCEPTION 'FINANCIAL_AGENT_AUTHORIZATION_FAILED' USING ERRCODE = '42501';
  END IF;
  IF char_length(p_user_message) NOT BETWEEN 1 AND 4000
     OR char_length(p_assistant_message) NOT BETWEEN 1 AND 4000 THEN
    RAISE EXCEPTION 'FINANCIAL_AGENT_MESSAGE_INVALID' USING ERRCODE = '22023';
  END IF;

  UPDATE public.financial_agent_conversations
  SET revision = revision + 1
  WHERE id = p_conversation_id
    AND user_id = p_user_id
    AND employer_id = p_employer_id
    AND revision = p_expected_revision
    AND status = 'ACTIVE'
  RETURNING * INTO v_conversation;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('ok', FALSE, 'error_code', 'STALE_CONVERSATION_STATE');
  END IF;

  INSERT INTO public.financial_agent_messages (
    conversation_id, user_id, employer_id, role, content
  ) VALUES (
    p_conversation_id, p_user_id, p_employer_id, 'user', p_user_message
  )
  RETURNING jsonb_build_object(
    'id', id, 'role', role, 'content', content, 'created_at', created_at
  ) INTO v_user_message;

  INSERT INTO public.financial_agent_messages (
    conversation_id, user_id, employer_id, role, content
  ) VALUES (
    p_conversation_id, p_user_id, p_employer_id, 'assistant', p_assistant_message
  )
  RETURNING jsonb_build_object(
    'id', id, 'role', role, 'content', content, 'created_at', created_at
  ) INTO v_assistant_message;

  RETURN jsonb_build_object(
    'ok', TRUE,
    'conversation', to_jsonb(v_conversation),
    'messages', jsonb_build_array(v_user_message, v_assistant_message)
  );
END;
$$;

REVOKE ALL ON FUNCTION public.append_financial_agent_turn(
  UUID, UUID, UUID, INTEGER, TEXT, TEXT
) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.append_financial_agent_turn(
  UUID, UUID, UUID, INTEGER, TEXT, TEXT
) TO service_role;

COMMIT;
